export const DICTIONARIES: Record<Locale, Dict> = {
  en: EN,
  es: translateSet(ES),
  fr: translateSet(FR),
  de: translateSet(DE),
  'pt-BR': translateSet(PT_BR),
  ar: translateSet(AR),
  hi: translateSet(HI),
  'zh-CN': translateSet(ZH_CN),
  ja: translateSet(JA),
  ru: translateSet(RU),
};

export function resolveLocale(input?: string | null): Locale {
  if (!input) return DEFAULT_LOCALE;
  const exact = LOCALES.find((locale) => locale.toLowerCase() === input.toLowerCase());
  if (exact) return exact;
  const base = input.toLowerCase().split('-')[0];
  return LOCALES.find((locale) => locale.toLowerCase().split('-')[0] === base) ?? DEFAULT_LOCALE;
}

export function isRTL(locale: Locale): boolean {
  return RTL_LOCALES.has(locale);
}

export function t(locale: Locale, key: string, vars: Record<string, string | number> = {}): string {
  const template = DICTIONARIES[locale][key] ?? DICTIONARIES[DEFAULT_LOCALE][key] ?? key;
  return template.replace(/\{\{(.*?)\}\}/g, (_, raw) => String(vars[raw.trim()] ?? ''));
}

export function localeOptions() {
  return LOCALES.map((locale) => ({ value: locale, label: LOCALE_LABELS[locale] }));
}
